export function resolveItemAccent(
  itemName: string,
  categoryName: string,
): string {
  for (const rule of FLAVOR_RULES) {
    if (rule.re.test(itemName)) return rule.color;
  }
  return CATEGORY_ACCENT[categoryName] ?? FALLBACK_ACCENT;
}
